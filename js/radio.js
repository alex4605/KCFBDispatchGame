function fitState(inc){
 const d=KIND[inc.k];let als=false,amb=false,cmd=false;
 for(const u of onScene(inc)){
  if(u.code==='41')cmd=true;
  if(u.code==='91'){if(u.st==='work')amb=true;if(u.tp&&(u.st==='work'||u.st==='tx'))als=true}}
 return{inc,d,als,amb,cmd,pol:inc.pol===2||!!d.police||!!d.tac,trap:inc.pm.trap>0,eff:effLines(inc),
  out:!!(OUTK[inc.k]||d.wild||inc.z==='hiway'||inc.z==='forest'),
  tx:inc.phs.some(p=>/車內照護|到院交接|後送|送醫/.test(p)),
  restr:!!BEHAVK[inc.k]||inc.need.some(g=>g.item==='約束器材')}}
function pickFit(list,inc,txt){
 const s=fitState(inc);
 const ok=list.filter(e=>{const t=txt?txt(e):e;
  for(const r of FITS)if(r[0].test(t)&&!r[1](s))return false;
  return true});
 return ok.length?pick(ok):null}
